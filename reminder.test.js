const assert=require('node:assert/strict');
const {reminderOccurrence,updateTask}=require('./logic');
const local=(y,m,d,h=0,min=0)=>new Date(y,m-1,d,h,min).toISOString();
const ts=s=>Date.parse(s);
const base={id:'x',title:'test',completed:false,dueAt:local(2026,11,12,10)};
let task={...base,reminderRule:{type:'offset',amount:30,unit:'minutes',startAt:local(2026,11,1)}};
assert.equal(reminderOccurrence(task,ts(local(2026,11,12,9,29))),null);
assert.equal(reminderOccurrence(task,ts(local(2026,11,12,9,30))),local(2026,11,12,9,30));
assert.equal(reminderOccurrence({...task,reminderRule:{...task.reminderRule,startAt:local(2026,11,12,9,45)}},ts(local(2026,11,12,9,50))),null);
assert.equal(reminderOccurrence({...task,lastOccurrenceAt:local(2026,11,12,9,30)},ts(local(2026,11,12,11))),null);
assert.equal(reminderOccurrence({...base,reminderRule:{type:'offset',amount:0,unit:'days',startAt:local(2026,11,1)}},ts(local(2026,11,12,10))),null);
const daily={...base,reminderRule:{type:'daily',time:'09:00',startAt:local(2026,11,10,10)}};
assert.equal(reminderOccurrence(daily,ts(local(2026,11,10,12))),null);
assert.equal(reminderOccurrence(daily,ts(local(2026,11,12,9,30))),local(2026,11,12,9));
assert.equal(reminderOccurrence(daily,ts(local(2026,11,12,10))),null);
assert.equal(reminderOccurrence({...daily,lastOccurrenceAt:local(2026,11,12,9)},ts(local(2026,11,12,11))),null);
const weekly={...base,dueAt:local(2026,11,19,9),reminderRule:{type:'weekly',weekday:4,time:'09:00',startAt:local(2026,11,1)}};
assert.equal(reminderOccurrence(weekly,ts(local(2026,11,18,10))),local(2026,11,12,9));
assert.equal(reminderOccurrence(weekly,ts(local(2026,11,19,10))),null);
assert.equal(reminderOccurrence({...weekly,completed:true},ts(local(2026,11,19,10))),null);
assert.equal(reminderOccurrence({...base,reminderRule:null,reminderAt:local(2026,11,1)},ts(local(2026,11,2))),null);
assert.equal(reminderOccurrence({completed:false,reminderAt:local(2026,11,1)},ts(local(2026,11,2))),local(2026,11,1));
assert.equal(reminderOccurrence({completed:false,reminderAt:local(2026,11,1),remindedAt:local(2026,11,1)},ts(local(2026,11,2))),null);
const recovered=updateTask({...daily,completed:true},{completed:false},ts(local(2026,11,11,10)));
assert.equal(reminderOccurrence(recovered,ts(local(2026,11,11,10))),null);
assert.equal(reminderOccurrence(recovered,ts(local(2026,11,12,9))),local(2026,11,12,9));
console.log('周期与一次提醒、边界、兼容及恢复测试通过');
